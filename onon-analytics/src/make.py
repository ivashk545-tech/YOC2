def head(kicker, title, lead=None):
    s = f'<div class="kicker">{kicker}</div><h1>{title}</h1>'
    if lead: s += f'<p class="lead">{lead}</p>'
    return f'<div class="hd">{s}</div>'

def fig(src, cap, h, cls=''):
    return (f'<figure class="fig {cls}"><div class="imgbox" style="{"height:%dpx" % h if h else ""}"><img src="{src}"></div>'
            f'<figcaption>{cap}</figcaption></figure>')

def table(head_cells, rows, cls='', widths=None):
    cg = ''
    if widths: cg = '<colgroup>' + ''.join(f'<col style="width:{w}">' for w in widths) + '</colgroup>'
    h = '<tr>' + ''.join(f'<th>{c}</th>' for c in head_cells) + '</tr>'
    b = ''.join('<tr>' + ''.join(f'<td>{m3(c)}</td>' for c in r) + '</tr>' for r in rows)
    return f'<table class="tbl {cls}">{cg}<thead>{h}</thead><tbody>{b}</tbody></table>'

