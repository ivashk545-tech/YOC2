def m3(s):
    return s.replace('м³', 'м<sup>3</sup>')

# ---------- decorative contour lines ----------
def contours(w, h, centers, n=14, color=LIME, op=0.18, seed=3):
    rnd = random.Random(seed)
    out = []
    for (cx, cy, R) in centers:
        ph = [rnd.uniform(0, 6.28) for _ in range(5)]
        amp = [rnd.uniform(0.03, 0.09) for _ in range(5)]
        for k in range(1, n + 1):
            r0 = R * k / n
            pts = []
            for t in range(0, 181):
                th = 2 * math.pi * t / 180
                f = 1 + sum(amp[i] * (1 + k / n) * math.sin((i + 2) * th + ph[i] + k * 0.12) for i in range(5))
                pts.append((cx + r0 * f * math.cos(th) * 1.35, cy + r0 * f * math.sin(th)))
            d = 'M' + ' L'.join(f'{x:.1f},{y:.1f}' for x, y in pts) + 'Z'
            out.append(f'<path d="{d}" fill="none" stroke="{color}" stroke-width="1" opacity="{op * (0.55 + 0.45 * k / n):.2f}"/>')
    return f'<svg class="bgsvg" viewBox="0 0 {w} {h}" width="{w}" height="{h}">{"".join(out)}</svg>'

