def resource_chart(unit, geo, rec, lo, hi, vmax, col, dark):
    H, base, x0 = 250, 196, 60
    Y = lambda v: base - v / vmax * 160
    s = f'<rect x="{x0}" y="{Y(min(hi, vmax)):.0f}" width="{CW-x0}" height="{Y(lo)-Y(min(hi, vmax)):.0f}" fill="{LIME}" opacity="{.25 if dark else .45}" rx="8"/>'
    for i, (lab, v, c) in enumerate([('геологические ресурсы', geo, col), ('извлекаемые запасы', rec, CREAM if dark else FOREST)]):
        cx = x0 + (CW - x0) * (0.27 + 0.46 * i)
        s += (f'<rect x="{cx-70:.0f}" y="{Y(v):.0f}" width="140" height="{base-Y(v):.0f}" rx="14" fill="{c}"/>'
              f'<text x="{cx:.0f}" y="{Y(v)-12:.0f}" text-anchor="middle" class="c-val">{str(v).replace(".", ",")}</text>'
              f'<text x="{cx:.0f}" y="{base+30}" text-anchor="middle" class="c-note">{lab}</text>')
    s += f'<line x1="{x0}" x2="{CW}" y1="{base}" y2="{base}" stroke="currentColor" opacity=".3"/>'
    s += f'<text x="0" y="{base}" class="c-note">{unit}</text>'
    return svg(CW, H, s)

